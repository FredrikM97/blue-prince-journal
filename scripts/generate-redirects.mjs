// Derives dist/_redirects from the app routes declared in __root.tsx, so the
// Cloudflare Pages SPA rewrite list can never drift from the actual routes.
import { readFileSync, writeFileSync } from "node:fs";

const rootRouteSource = readFileSync(new URL("../src/routes/__root.tsx", import.meta.url), "utf8");

const routeSegments = [...rootRouteSource.matchAll(/path:\s*"([^"]+)"/g)]
  .map((match) => match[1])
  .filter((path) => path !== "/");

if (routeSegments.length === 0) {
  throw new Error("No app route segments found in __root.tsx — refusing to write an empty _redirects file.");
}

const lines = [
  "# Generated by scripts/generate-redirects.mjs from src/routes/__root.tsx — do not edit by hand.",
  "# Known SPA routes rewrite to the app shell with a real 200; everything else falls through to 404.html.",
  ...routeSegments.map((path) => `/${path}      /index.html   200`),
  "",
];

writeFileSync(new URL("../dist/_redirects", import.meta.url), lines.join("\n"));
